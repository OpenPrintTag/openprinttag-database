#!/usr/bin/env python3
"""
One-off migration: diameters from micrometers (µm) to millimeters (mm).

Follows openprinttag-architecture PR #49 ("Use mm instead of µm for diameters").
Affected fields:

  - filament_diameter            (material package)  1750 -> 1.75
  - filament_diameter_tolerance  (material package)    30 -> 0.03
  - min_nozzle_diameter          (material properties) 400 -> 0.4

The files are edited as text (not re-dumped through a YAML library), so comments,
key order and formatting stay untouched and the diff contains only the changed lines.
File names (e.g. ``...-2850um-1kg.yaml``) and slugs are intentionally NOT changed.

Usage:
    python scripts/migrate_units_mm.py            # dry run (default), only reports
    python scripts/migrate_units_mm.py --apply    # rewrite the files

The script is safe to run repeatedly: a value that already looks like mm
(contains a decimal point, or is too small to be a valid µm value) is left alone.
Values that cannot be classified reliably are reported as ambiguous and never changed.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation
from pathlib import Path

# field -> smallest integer that can still be a µm value (below it, it is taken as mm
# that was already migrated, e.g. "3" for 3 mm).  None = cannot be told apart, so integers
# under AMBIGUOUS_BELOW are reported instead of converted.
FIELDS: dict[str, dict] = {
    "filament_diameter": {"min_um": 100, "new_min": Decimal("0.1"), "new_max": Decimal("1000")},
    "min_nozzle_diameter": {"min_um": 10, "new_min": Decimal("0.01"), "new_max": Decimal("100")},
    # Tolerance: new range 0-15 mm. Integers >= 16 can only be µm; smaller ones are ambiguous.
    "filament_diameter_tolerance": {"min_um": 16, "new_min": Decimal("0"), "new_max": Decimal("15")},
}

LINE_RE = re.compile(
    r"^(?P<indent>[ \t]*)(?P<key>" + "|".join(FIELDS) + r"):"
    r"(?P<sep>[ \t]+)(?P<value>[^\s#]+)(?P<tail>[ \t]*(?:#.*)?)(?P<eol>\r?\n?)$"
)


@dataclass
class Result:
    changed_files: list[Path] = field(default_factory=list)
    converted: int = 0
    already_mm: int = 0
    ambiguous: list[str] = field(default_factory=list)
    out_of_range: list[str] = field(default_factory=list)


def um_to_mm(value: str) -> str:
    """Convert an integer µm string to a plain decimal mm string ('1750' -> '1.75', '3000' -> '3')."""
    mm = Decimal(value) / 1000
    text = format(mm, "f")
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text or "0"


def convert_line(line: str):
    """Return (new_line, status) for one line; status in {None, 'converted', 'mm', 'ambiguous', 'range'}."""
    m = LINE_RE.match(line)
    if not m:
        return line, None
    key, raw = m["key"], m["value"]
    spec = FIELDS[key]

    try:
        number = Decimal(raw)
    except InvalidOperation:
        return line, "ambiguous"  # e.g. a string or placeholder - never guess

    if "." in raw or "e" in raw.lower():
        return line, "mm"  # decimal notation => already migrated
    if number < spec["min_um"]:
        if number == 0:
            return line, "mm"  # zero is the same in both units
        # Too small for a real µm value. For tolerance 1..15 it could be either unit.
        if key == "filament_diameter_tolerance" and number > 0:
            return line, "ambiguous"
        return line, "mm" if number > 0 else "ambiguous"

    mm = Decimal(um_to_mm(raw))
    if not (spec["new_min"] <= mm <= spec["new_max"]):
        return line, "range"
    new = f'{m["indent"]}{key}:{m["sep"]}{um_to_mm(raw)}{m["tail"]}{m["eol"]}'
    return new, "converted"


def migrate_file(path: Path, apply: bool, result: Result) -> None:
    # newline="" keeps original line endings byte for byte
    with path.open("r", encoding="utf-8", newline="") as fh:
        original = fh.readlines()

    out, touched = [], False
    for number, line in enumerate(original, 1):
        new, status = convert_line(line)
        if status == "converted":
            result.converted += 1
            touched = True
        elif status == "mm":
            result.already_mm += 1
        elif status == "ambiguous":
            result.ambiguous.append(f"{path}:{number}: {line.strip()}")
        elif status == "range":
            result.out_of_range.append(f"{path}:{number}: {line.strip()}")
        out.append(new)

    if touched:
        result.changed_files.append(path)
        if apply:
            with path.open("w", encoding="utf-8", newline="") as fh:
                fh.writelines(out)


def migrate(data_dir: Path, apply: bool) -> Result:
    result = Result()
    for path in sorted(data_dir.rglob("*.yaml")):
        if path.name == "manifest.yaml":
            continue  # auto-generated by CI
        migrate_file(path, apply, result)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-dir", type=Path, default=Path(__file__).resolve().parent.parent / "data")
    parser.add_argument("--apply", action="store_true", help="write changes (default: dry run)")
    args = parser.parse_args(argv)

    if not args.data_dir.is_dir():
        print(f"Data directory not found: {args.data_dir}", file=sys.stderr)
        return 2

    result = migrate(args.data_dir, args.apply)

    mode = "APPLIED" if args.apply else "DRY RUN (nothing written, use --apply)"
    print(f"[{mode}]")
    print(f"  files to change/changed : {len(result.changed_files)}")
    print(f"  values converted        : {result.converted}")
    print(f"  already in mm (skipped) : {result.already_mm}")
    print(f"  ambiguous (unchanged)   : {len(result.ambiguous)}")
    print(f"  out of range (unchanged): {len(result.out_of_range)}")
    for label, items in (("AMBIGUOUS", result.ambiguous), ("OUT OF RANGE", result.out_of_range)):
        for item in items:
            print(f"  {label}: {item}", file=sys.stderr)

    return 1 if (result.ambiguous or result.out_of_range) else 0


if __name__ == "__main__":
    sys.exit(main())
